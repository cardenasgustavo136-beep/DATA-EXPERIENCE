# 3.1 Temperatura: Google Sheets convirtió algunos decimales en fechas
def interpretacion_datos(v):
    v = str(v)
    if "/" in v:
        dia, mes, _ = v.split("/")
        return float(f"{int(dia)}.{int(mes)}")
    return float(v)

df["temperatura_C"] = df["temperatura_C"].map(interpretacion_datos)

# 3.2 Texto: quitar espacios y unificar mayúsculas
df["turno"] = df["turno"].str.strip().str.capitalize()
df["linea"] = df["linea"].str.strip().str.upper()

# 3.3 Corregir la ñ si llegó mal codificada
df["turno"] = df["turno"].replace({"MaÃ±ana": "Mañana", "Ma?ana": "Mañana", "Manana": "Mañana"})

# 3.4 Orden de categorías tomado de los datos reales (evita el ValueError)
