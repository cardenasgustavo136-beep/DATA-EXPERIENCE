f, p = stats.f_oneway(*[g["tasa_defectos_pct"] for _, g in df.groupby("linea")])
tabla("12b", "H2: ANOVA entre líneas",
      "tasa_defectos_pct separada por linea",
      f"F = {f:.3f}, p = {p:.4g}")

alta = df.loc[df["temperatura_C"] > 30, "tasa_defectos_pct"]
normal = df.loc[df["temperatura_C"] <= 30, "tasa_defectos_pct"]
t, p = stats.ttest_ind(alta, normal, equal_var=False)
tabla("12c", "H3: t-test temperatura > 30 °C vs resto",
      "tasa_defectos_pct según temperatura_C",
      f"t = {t:.3f}, p = {p:.4g}")